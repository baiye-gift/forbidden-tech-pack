source=(ROOT/'src/Game/Localization/STRINGS.cs').read_text(encoding='utf-8')
body=source.split('public static class MATTER {',1)[1].split('public static class SAFEREMOVAL',1)[0]
fields=re.findall(r'public static LocString (\w+) = "((?:[^"\\]|\\.)*)";',body)
if set(k for k,v in fields)!=set(ZH):raise ValueError('Missing or obsolete translation')
all_fields={};stack=[]
for line in source.splitlines():
    cls=re.search(r'public static class (\w+) \{',line)
    field=re.search(r'public static LocString (\w+) = "((?:[^"\\]|\\.)*)";',line)
    if cls:stack.append(cls.group(1))
    elif field:all_fields['.'.join(stack+[field.group(1)])]=json.loads('"'+field.group(2)+'"')
    elif line.strip()=='}':stack.pop()
if not set(EXTRA_ZH).issubset(all_fields):raise ValueError('Missing mass-energy field')
marker='\n# Shared matter processing text (generated by scripts/sync-localization.py)\n'
for lang in ['en','zh']:
    path=ROOT/f'packaging/translations/{lang}.po'
    text=path.read_text(encoding='utf-8').split(marker)[0].rstrip()
    # Replace earlier entries for updated items rather than producing duplicate contexts.
    for key in EXTRA_ZH:
        text=re.sub(r'(?m)^msgctxt '+re.escape(json.dumps(key))+r'\n(?:[^\n]+\n?)*', '', text)
    text=text.rstrip()+marker
    for key,en in fields:
        en=json.loads('"'+en+'"')
        text+='\nmsgctxt '+json.dumps('STRINGS.UI.MATTER.'+key)+'\nmsgid '+json.dumps(en,ensure_ascii=False)+'\nmsgstr '+json.dumps(ZH[key] if lang=='zh' else en,ensure_ascii=False)+'\n'
    for key,zh in EXTRA_ZH.items():
        en=all_fields[key]
        text+='\nmsgctxt '+json.dumps(key)+'\nmsgid '+json.dumps(en,ensure_ascii=False)+'\nmsgstr '+json.dumps(zh if lang=='zh' else en,ensure_ascii=False)+'\n'
    path.write_text(text,encoding='utf-8',newline='\n')
print(f'Synchronized {len(fields)+len(EXTRA_ZH)} bilingual entries.')
